#!/usr/bin/env node
// Builds manifest.json from canvas.json and the board files in this folder.
// Run after re-exporting the canvas: `node specs/design-system/canvas/build-manifest.mjs`.
// The manifest is the index the pixel-diff pipeline (feature 007) reads; see
// .claude/skills/design-fidelity/SKILL.md.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const canvas = JSON.parse(readFileSync(join(here, 'canvas.json'), 'utf8'))
const previous = (() => {
  try {
    return JSON.parse(readFileSync(join(here, 'manifest.json'), 'utf8'))
  } catch {
    return null
  }
})()

// Which feature builds each screen (specs/ROADMAP.md).
const FEATURE = [
  [['01', '02', '03', '04', '05', '06'], '010-first-visit-landing'],
  [['07', '08', '09', '10', '11', '12', '13', '14', '40'], '012-mobile-quick-match'],
  [['15', '16', '17', '18', '19'], '011-mobile-creators'],
  [['20', '21', '22', '23'], '009-otp-sign-in'],
  [['24', '25', '26'], '013-client-account'],
  [['27', '28', '29', '30', '31', '32'], '014-creator-account'],
  [['33', '34', '35', '36', '38'], '015-mobile-content'],
  [['37', '39'], '007-mobile-foundation'],
]
const featureOf = (id) => FEATURE.find(([ids]) => ids.includes(id))?.[1] ?? null

// Text-heavy boards: anti-aliasing differs more between Chromium and Skia's test rasteriser.
const TEXT_HEAVY = new Set(['33', '34', '35', '36'])
// Designer-made variants of another screen: used to validate the derived dark/Arabic references.
const DESIGNER_VARIANT = { '42': { of: '21', variant: 'ar-dark' }, '43': { of: '13', variant: 'ar-dark' } }

// Selectors whose boxes the geometry gate compares (±1 logical px), when the board has them.
const BOX_CANDIDATES = { header: '.hd', wordmark: '.wm', h1: '.h1', topHit: '.top' }
// Boards whose heading has no `.h1` class: a stable selector for it (feature 007, T033).
const EXTRA_BOXES = { '37': { h1: 'main h1' }, '39': { h1: 'main h1' } }

const screens = []
for (const board of canvas.order) {
  const entry = canvas.boards[board]
  if (entry.page !== 'screens') continue
  const match = /^(\d{2}) · (.+)$/.exec(entry.title ?? '')
  if (!match) throw new Error(`Board ${board} has no "NN · title"`)
  const [, id, title] = match
  const html = readFileSync(join(here, board), 'utf8')
  const sha256 = createHash('sha256').update(html).digest('hex')
  const classes = new Set([...html.matchAll(/class="([^"]+)"/g)].flatMap((m) => m[1].split(/\s+/)))
  const boxes = {
    ...Object.fromEntries(Object.entries(BOX_CANDIDATES).filter(([, sel]) => classes.has(sel.slice(1)))),
    ...(EXTRA_BOXES[id] ?? {}),
  }
  const isWeb = entry.w > 600
  const designer = DESIGNER_VARIANT[id]
  const prev = previous?.screens?.find((s) => s.id === id)
  screens.push({
    id,
    title,
    board,
    w: entry.w,
    h: entry.h,
    target: isWeb ? 'web' : 'mobile',
    feature: isWeb || designer ? null : featureOf(id),
    variants: designer ? [designer.variant] : isWeb ? ['en-light'] : ['en-light', 'en-dark', 'ar-light', 'ar-dark'],
    ...(designer ? { variantOf: designer.of } : {}),
    boxes,
    ...(TEXT_HEAVY.has(id)
      ? { threshold: 0.02, reason: 'Long running text: more anti-aliased glyph edges per pixel.' }
      : {}),
    sha256,
    ...(prev && prev.sha256 !== sha256 ? { changedSinceLastExport: true } : {}),
  })
}
screens.sort((a, b) => a.id.localeCompare(b.id))

const ds = canvas.designSystems?.[0]
const manifest = {
  $comment:
    'Generated by build-manifest.mjs. Do not edit by hand; re-export the canvas and rerun. Screen ids are the canvas numbers (01-43).',
  canvas: {
    title: canvas.title,
    url: 'https://claude.ai/artifact/HeYx13fA2XFumiydvHeoTV',
    version: process.env.CANVAS_VERSION ?? previous?.canvas?.version ?? null,
    exportedAt: process.env.EXPORTED_AT ?? previous?.canvas?.exportedAt ?? new Date().toISOString(),
  },
  designSystem: ds ? { title: ds.title, url: ds.artifact, version: ds.version } : null,
  defaults: {
    scale: 2,
    threshold: 0.01,
    geometryTolerancePx: 1,
    reducedMotion: true,
  },
  screens,
}
writeFileSync(join(here, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
console.log(`manifest.json: ${screens.length} screens`)
