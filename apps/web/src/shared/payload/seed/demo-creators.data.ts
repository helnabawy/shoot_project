// The demo creators (local, e2e and Lighthouse CI only; refused on any other host). Plain data with
// no imports beyond types, so end-to-end tests derive their expectations from it instead of
// repeating counts. Every creator has an illustrated portrait, a gender (private: it drives Quick
// Match's "shot by"), a nationality (ISO code) and whole years of experience (002 FR-011).
//
// Roles the tests rely on: D2222 is the one featured creator (the directory's Top Hit) and holds the demo quotation; D5555 is in review;
// D6666 is listed without samples; D8888 is paused by its owner. Everyone else is listed.

